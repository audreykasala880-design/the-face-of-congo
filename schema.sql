CREATE TABLE IF NOT EXISTS candidatures (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  nom VARCHAR(120) NOT NULL,
  postnom VARCHAR(120) NOT NULL DEFAULT '',
  prenom VARCHAR(120) NOT NULL,
  sexe VARCHAR(20) NOT NULL,
  telephone VARCHAR(40) NOT NULL,
  nom_scene VARCHAR(120) NOT NULL DEFAULT '',
  date_naissance DATE NOT NULL,
  ville VARCHAR(120) NOT NULL,
  email VARCHAR(254) NOT NULL,
  taille SMALLINT UNSIGNED NOT NULL,
  profession VARCHAR(160) NOT NULL DEFAULT '',
  experience VARCHAR(20) NOT NULL DEFAULT 'Non',
  type_modele JSON NOT NULL,
  motivation TEXT NOT NULL,
  qualites TEXT NOT NULL,
  signature VARCHAR(240) NOT NULL,
  date_soumission DATE NOT NULL,
  photo_portrait_public_id VARCHAR(255) NULL,
  photo_portrait_format VARCHAR(16) NULL,
  photo_pied_public_id VARCHAR(255) NULL,
  photo_pied_format VARCHAR(16) NULL,
  photo_artistique_public_id VARCHAR(255) NULL,
  photo_artistique_format VARCHAR(16) NULL,
  photo_portrait MEDIUMBLOB NULL,
  photo_portrait_mime VARCHAR(32) NULL,
  photo_pied MEDIUMBLOB NULL,
  photo_pied_mime VARCHAR(32) NULL,
  photo_artistique MEDIUMBLOB NULL,
  photo_artistique_mime VARCHAR(32) NULL,
  statut ENUM('Reçue', 'En cours', 'Acceptée', 'Refusée') NOT NULL DEFAULT 'Reçue',
  cree_le TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  INDEX idx_candidatures_cree_le (cree_le),
  INDEX idx_candidatures_statut (statut)
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8mb4 COLLATE=utf8mb4_general_ci;